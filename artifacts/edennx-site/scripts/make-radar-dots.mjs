// Builds src/lib/radarLockup.ts from Amelia's layered EdenRadar lockup
// (RICO/marketing/brand/logos/edenradar/edenradar-lockup-layered.svg): the dots
// split into the top and bottom domes, plus the outlined wordmark and tagline,
// so the large lockup can move each part on its own.
// Run: node scripts/make-radar-dots.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SRC = "/Users/richa/eden/RICO/marketing/brand/logos/edenradar/edenradar-lockup-layered.svg";
const svg = readFileSync(SRC, "utf8");
const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
const dots = [...svg.matchAll(/<circle cx="([\d.]+)" cy="([\d.]+)" r="([\d.]+)"/g)].map((m) => m.slice(1, 4).map(Number));
const path = (id) => svg.match(new RegExp(`id="${id}"[^>]*\\sd="([^"]+)"`))[1];

// The wordmark sits between y 852 and 1159; anything above it is the top dome.
const top = dots.filter(([, cy]) => cy < 852);
const bottom = dots.filter(([, cy]) => cy > 1159);

writeFileSync(
  fileURLToPath(new URL("../src/lib/radarLockup.ts", import.meta.url)),
  `// Generated by scripts/make-radar-dots.mjs from Amelia's layered EdenRadar lockup.\n` +
    `export const LOCKUP_VIEWBOX = ${JSON.stringify(viewBox)};\n` +
    `export const RADAR_TOP: [number, number, number][] = ${JSON.stringify(top)};\n` +
    `export const RADAR_BOTTOM: [number, number, number][] = ${JSON.stringify(bottom)};\n` +
    `export const WORDMARK_EDEN = ${JSON.stringify(path("wordmark-eden"))};\n` +
    `export const WORDMARK_RADAR = ${JSON.stringify(path("wordmark-radar"))};\n` +
    `export const TAGLINE = ${JSON.stringify(path("tagline"))};\n`,
);
console.log(`dots ${dots.length}: top ${top.length}, bottom ${bottom.length}`);
