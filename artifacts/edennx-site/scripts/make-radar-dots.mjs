// Builds src/lib/radarDots.ts from public/images/marks/mark-radar.svg: the dot
// globe's circles split into the top and bottom domes, so the large EdenRadar
// lockup can move each dome on its own. Run: node scripts/make-radar-dots.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const at = (p) => fileURLToPath(new URL(p, import.meta.url));
const svg = readFileSync(at("../public/images/marks/mark-radar.svg"), "utf8");
const dots = [...svg.matchAll(/<circle cx="([\d.]+)" cy="([\d.]+)" r="([\d.]+)"/g)].map((m) => m.slice(1, 4).map(Number));
const top = dots.filter(([, cy]) => cy < 50);
const bottom = dots.filter(([, cy]) => cy > 50);

writeFileSync(
  at("../src/lib/radarDots.ts"),
  `// Generated by scripts/make-radar-dots.mjs from the EdenRadar dot globe. [cx, cy, r] in a 100 x 100 box.\n` +
    `export const RADAR_TOP: [number, number, number][] = ${JSON.stringify(top)};\n` +
    `export const RADAR_BOTTOM: [number, number, number][] = ${JSON.stringify(bottom)};\n`,
);
console.log(`top ${top.length}, bottom ${bottom.length}`);
